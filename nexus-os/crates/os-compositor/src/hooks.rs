use crossbeam_channel::Sender;
use os_core::window::WindowHandle;
use parking_lot::Mutex;
use std::sync::atomic::{AtomicU32, Ordering};
use std::thread::JoinHandle;
use tracing::info;
use windows::Win32::Foundation::{HMODULE, HWND, LPARAM, WPARAM};
use windows::Win32::System::Threading::GetCurrentProcessId;
use windows::Win32::UI::Accessibility::{SetWinEventHook, UnhookWinEvent, HWINEVENTHOOK};
use windows::Win32::UI::WindowsAndMessaging::{
    DispatchMessageW, GetMessageW, PostThreadMessageW, MSG, OBJID_WINDOW,
    WINEVENT_OUTOFCONTEXT, WINEVENT_SKIPOWNPROCESS, WM_QUIT,
    EVENT_OBJECT_CREATE, EVENT_OBJECT_DESTROY, EVENT_OBJECT_HIDE, EVENT_OBJECT_SHOW,
    EVENT_OBJECT_CLOAKED, EVENT_OBJECT_UNCLOAKED,
    EVENT_SYSTEM_FOREGROUND, EVENT_SYSTEM_MOVESIZEEND,
};

#[derive(Debug, Clone)]
pub enum WindowEvent {
    ForegroundChanged(WindowHandle),
    WindowCreated(WindowHandle),
    WindowDestroyed(WindowHandle),
    WindowShow(WindowHandle),
    WindowHide(WindowHandle),
    WindowCloaked(WindowHandle),
    WindowUncloaked(WindowHandle),
    MoveSizeEnd(WindowHandle),
}

#[derive(Clone, Copy)]
struct SendWinEventHook(HWINEVENTHOOK);
unsafe impl Send for SendWinEventHook {}
unsafe impl Sync for SendWinEventHook {}

static EVENT_SENDER: Mutex<Option<Sender<WindowEvent>>> = Mutex::new(None);
static HOOK_HANDLES: Mutex<Vec<SendWinEventHook>> = Mutex::new(Vec::new());
static OWN_PID: AtomicU32 = AtomicU32::new(0);

pub struct WinEventListener {
    thread_handle: Option<JoinHandle<()>>,
    thread_id: u32,
}

impl WinEventListener {
    pub fn start() -> anyhow::Result<(Self, crossbeam_channel::Receiver<WindowEvent>)> {
        let (tx, rx) = crossbeam_channel::unbounded();
        *EVENT_SENDER.lock() = Some(tx);
        OWN_PID.store(unsafe { GetCurrentProcessId() }, Ordering::SeqCst);

        let (thread_id_tx, thread_id_rx) = crossbeam_channel::bounded(1);

        let handle = std::thread::spawn(move || {
            let tid = unsafe { windows::Win32::System::Threading::GetCurrentThreadId() };
            let _ = thread_id_tx.send(tid);

            let events_to_hook = [
                (EVENT_SYSTEM_FOREGROUND, EVENT_SYSTEM_FOREGROUND),
                (EVENT_SYSTEM_MOVESIZEEND, EVENT_SYSTEM_MOVESIZEEND),
                (EVENT_OBJECT_CREATE, EVENT_OBJECT_HIDE),
                (EVENT_OBJECT_CLOAKED, EVENT_OBJECT_UNCLOAKED),
            ];

            let mut hooks = Vec::new();
            for (min_evt, max_evt) in events_to_hook {
                let hook = unsafe {
                    SetWinEventHook(
                        min_evt,
                        max_evt,
                        HMODULE::default(),
                        Some(Self::win_event_proc),
                        0,
                        0,
                        WINEVENT_OUTOFCONTEXT | WINEVENT_SKIPOWNPROCESS,
                    )
                };
                if !hook.is_invalid() {
                    hooks.push(SendWinEventHook(hook));
                }
            }

            *HOOK_HANDLES.lock() = hooks;
            info!("WinEvent hooks installed successfully with re-entrancy protection");

            let mut msg = MSG::default();
            unsafe {
                while GetMessageW(&mut msg, HWND::default(), 0, 0).as_bool() {
                    if msg.message == WM_QUIT {
                        break;
                    }
                    DispatchMessageW(&msg);
                }
            }

            let hooks = std::mem::take(&mut *HOOK_HANDLES.lock());
            for h in hooks {
                let _ = unsafe { UnhookWinEvent(h.0) };
            }
        });

        let thread_id = thread_id_rx.recv().unwrap_or(0);

        Ok((
            Self {
                thread_handle: Some(handle),
                thread_id,
            },
            rx,
        ))
    }

    unsafe extern "system" fn win_event_proc(
        _hook: HWINEVENTHOOK,
        event: u32,
        hwnd: HWND,
        id_object: i32,
        _id_child: i32,
        _id_event_thread: u32,
        _dwms_event_time: u32,
    ) {
        if id_object != OBJID_WINDOW.0 || hwnd.0.is_null() {
            return;
        }

        let handle = WindowHandle::new(hwnd);

        // Strict Re-entrancy Guard: never process events generated by our own daemon
        let own_pid = OWN_PID.load(Ordering::Relaxed);
        if handle.pid() == own_pid {
            return;
        }

        let event_opt = match event {
            EVENT_SYSTEM_FOREGROUND => Some(WindowEvent::ForegroundChanged(handle)),
            EVENT_OBJECT_CREATE => Some(WindowEvent::WindowCreated(handle)),
            EVENT_OBJECT_DESTROY => Some(WindowEvent::WindowDestroyed(handle)),
            EVENT_OBJECT_SHOW => Some(WindowEvent::WindowShow(handle)),
            EVENT_OBJECT_HIDE => Some(WindowEvent::WindowHide(handle)),
            EVENT_OBJECT_CLOAKED => Some(WindowEvent::WindowCloaked(handle)),
            EVENT_OBJECT_UNCLOAKED => Some(WindowEvent::WindowUncloaked(handle)),
            EVENT_SYSTEM_MOVESIZEEND => Some(WindowEvent::MoveSizeEnd(handle)),
            _ => None,
        };

        if let Some(evt) = event_opt {
            if let Some(ref sender) = *EVENT_SENDER.lock() {
                let _ = sender.try_send(evt);
            }
        }
    }
}

impl Drop for WinEventListener {
    fn drop(&mut self) {
        if self.thread_id != 0 {
            unsafe {
                let _ = PostThreadMessageW(self.thread_id, WM_QUIT, WPARAM(0), LPARAM(0));
            }
        }
        if let Some(handle) = self.thread_handle.take() {
            let _ = handle.join();
        }
    }
}
